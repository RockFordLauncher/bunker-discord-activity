from card_generators.common import VALID_SPECIAL_ACTIONS


def _format_quality_list(items):
    seen = set()
    res = []
    for idx, (text, quality) in enumerate(items, 1):
        t = text.strip()
        if not t or t in seen:
            raise ValueError(f"Duplicate or empty item: {t!r}")
        if quality not in ("good", "neutral", "bad"):
            raise ValueError(f"Invalid quality {quality!r} for {t!r}")
        seen.add(t)
        res.append({"id": idx, "text": t, "quality": quality})
    if len(res) != 100:
        raise ValueError(f"Expected 100 items, got {len(res)}")
    return res


