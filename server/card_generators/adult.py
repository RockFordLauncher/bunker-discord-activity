def _pack_main(good_list, neutral_list, bad_list):
    items = []
    idx = 1
    for text in good_list:
        items.append({"id": idx, "text": text, "quality": "good"})
        idx += 1
    for text in neutral_list:
        items.append({"id": idx, "text": text, "quality": "neutral"})
        idx += 1
    for text in bad_list:
        items.append({"id": idx, "text": text, "quality": "bad"})
        idx += 1
    return items


