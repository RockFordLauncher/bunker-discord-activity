VALID_SPECIAL_ACTIONS = (
    'immunity',
    'reveal',
    'swap',
    'peek',
    'skip_vote',
    'double_vote',
    'revive',
    'poison',
)


def _build_quality_cards(items):
    return [
        {"id": idx, "text": text, "quality": quality}
        for idx, (text, quality) in enumerate(items, 1)
    ]


def _build_specials(items):
    res = []
    for idx, (text, action, desc) in enumerate(items, 1):
        if action not in VALID_SPECIAL_ACTIONS:
            raise ValueError(f"Invalid special action: {action}")
        res.append({
            "id": idx,
            "text": text,
            "action": action,
            "description": desc,
        })
    return res


def _build_catastrophes(items):
    return [
        {"id": idx, "text": text, "description": desc}
        for idx, (text, desc) in enumerate(items, 1)
    ]


def _build_bunkers(items):
    return [
        {"id": idx, "text": text, "capacity": cap, "description": desc}
        for idx, (text, cap, desc) in enumerate(items, 1)
    ]


